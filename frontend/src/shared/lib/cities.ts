/**
 * Города — тот же фиксированный справочник, что на бэкенде
 * (backend/app/domain/identity/entities.py, список городов Tenant.city).
 * Предложный падеж — только для тех, что реально используются в текстах
 * витрины (например заголовок карусели «Магазины <города> в одном месте»).
 */
export const CITIES = [
  'Грозный',
  'Урус-Мартан',
  'Гудермес',
  'Шали',
  'Аргун',
  'Курчалой',
  'Ачхой-Мартан',
  'Наурская',
  'Другой',
] as const

const PREPOSITIONAL: Record<string, string> = {
  'Грозный': 'Грозного',
  'Урус-Мартан': 'Урус-Мартана',
  'Гудермес': 'Гудермеса',
  'Шали': 'Шали',
  'Аргун': 'Аргуна',
  'Курчалой': 'Курчалоя',
  'Ачхой-Мартан': 'Ачхой-Мартана',
  'Наурская': 'Наурской',
  'Другой': 'вашего города',
}

/** «Грозный» → «Грозного» (родительный, для «Магазины <города> в одном месте»). Неизвестный/пустой город → «вашего города». */
export function cityGenitive(city: string | null | undefined): string {
  if (!city) return 'вашего города'
  return PREPOSITIONAL[city] ?? city
}
