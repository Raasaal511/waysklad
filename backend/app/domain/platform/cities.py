"""Справочник городов магазина — первый рынок платформы (Чечня), список легко
расширить. Порядок — как в UI (крупные города сначала), 'Другой' — всегда
последним, для магазинов вне списка."""

CITIES: tuple[str, ...] = (
    "Грозный",
    "Урус-Мартан",
    "Гудермес",
    "Шали",
    "Аргун",
    "Курчалой",
    "Ачхой-Мартан",
    "Наурская",
    "Другой",
)

CITY_SET = frozenset(CITIES)


def is_valid_city(city: str) -> bool:
    return city in CITY_SET
