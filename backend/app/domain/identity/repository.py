from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from app.domain.identity.entities import Tenant, User, Warehouse


class ITenantRepository(Protocol):
    async def add(self, tenant: Tenant) -> Tenant: ...
    async def save(self, tenant: Tenant) -> Tenant: ...
    async def get(self, tenant_id: int) -> Tenant: ...
    async def get_by_slug(self, slug: str) -> Tenant | None: ...
    async def get_by_owner_chat_id(self, chat_id: str) -> Tenant | None:
        """Обратный поиск по Tenant.owner_telegram_chat_id — для обработки
        нажатий на inline-кнопки в уведомлениях владельцу (Telegram-бот
        должен понять, из какого магазина пришло нажатие, зная только chat_id
        отправителя, без сессии/токена)."""
        ...
    async def list_all(self) -> list[Tenant]: ...


@dataclass(frozen=True)
class UserSession:
    token_version: int
    last_seen_at: datetime | None


class IUserRepository(Protocol):
    async def touch_last_login(self, user_id: int, at: datetime) -> None:
        """Отметить вход. Отдельным методом, а не через save(): вход не должен
        перезаписывать остальные поля пользователя. Вход — тоже активность,
        поэтому last_seen_at сдвигается вместе с last_login_at."""
        ...

    async def touch_last_seen(self, user_id: int, at: datetime) -> None:
        """Отметить обращение с действующим токеном — точечно, как и вход."""
        ...

    async def add(self, user: User) -> User: ...
    async def get(self, user_id: int) -> User: ...
    async def get_by_phone(self, phone: str) -> User | None: ...
    async def list_by_tenant(self) -> list[User]: ...
    async def save(self, user: User) -> User: ...
    async def get_session(self, user_id: int) -> UserSession | None:
        """token_version и last_seen_at без полной загрузки — для проверки JWT на
        каждый запрос. None — пользователь не найден или деактивирован."""
        ...


class IWarehouseRepository(Protocol):
    async def add(self, warehouse: Warehouse) -> Warehouse: ...
    async def get(self, warehouse_id: int) -> Warehouse: ...
    async def update_details(
        self, warehouse_id: int, name: str, address: str, show_on_storefront: bool = False
    ) -> Warehouse:
        """Обновляет название, адрес и видимость на витрине, не трогая назначенных сотрудников."""
        ...
    async def set_photo(self, warehouse_id: int, photo: str) -> Warehouse:
        """Заменяет логотип склада (пустая строка — убрать логотип)."""
        ...
    async def list(self) -> list[Warehouse]: ...
    async def list_for_user(self, user_id: int) -> list[Warehouse]:
        """Только склады, назначенные этому пользователю (manager/seller/storekeeper)."""
        ...
    async def is_assigned(self, warehouse_id: int, user_id: int) -> bool: ...
    async def set_assignments(self, warehouse_id: int, user_ids: list[int]) -> Warehouse:
        """Полностью заменяет список сотрудников, привязанных к складу."""
        ...
    async def add_assignment(self, warehouse_id: int, user_id: int) -> None:
        """Добавляет привязку, не трогая остальных (для нового сотрудника)."""
        ...
    async def set_user_assignments(self, user_id: int, warehouse_ids: list[int]) -> None:
        """Полностью заменяет список складов конкретного сотрудника."""
        ...
