"""Склады, остатки которых витрина показывает покупателю.

Вынесено в одно место: тот же набор нужен каталогу, карточке товара,
похожим товарам, профилю магазина, резерву и заявке.
"""

from app.domain.identity.entities import Warehouse


def visible_warehouse_ids(warehouses: list[Warehouse]) -> set[int]:
    """Склады с галкой «показывать на витрине».

    Если такой галки нет ни у одного склада, витрина считает остаток по всем
    складам магазина. Причина: пустой набор отбрасывает все позиции остатка, и
    магазин целиком показывается как «нет в наличии» при живом остатке — так
    выглядел баг на проде 10.10.2026 (склад заводился с show_on_storefront=False,
    а переключатель лежит в карточке склада, куда владелец не заходит).

    «Показать всё» — безопасный отказ: витрина и так показывает только товары
    с show_on_storefront, то есть выбранные владельцем осознанно. Скрыть один
    склад из нескольких по-прежнему можно — запас включается, только когда не
    выбрано ни одного.
    """
    visible = {w.id for w in warehouses if w.show_on_storefront}
    return visible if visible else {w.id for w in warehouses}
